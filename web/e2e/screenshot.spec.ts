import { createSession, expect, expectTerminal, test, typeInTerminal } from './fixtures'

// Not a check: writes screenshots of the main states for a look (SCREENSHOTS=1).
test('screenshots', async ({ page, minbox }) => {
  test.skip(process.env.SCREENSHOTS !== '1', 'set SCREENSHOTS=1')
  test.setTimeout(180_000)
  const out = process.env.SCREENSHOT_DIR ?? 'test-results'
  const shot = async (name: string) => {
    await page.waitForTimeout(400)
    await page.screenshot({ path: `${out}/${name}.png` })
  }
  await page.emulateMedia({ colorScheme: process.env.LIGHT ? 'light' : 'dark' })
  await page.goto(minbox.url)
  await shot('00-empty')
  await page.getByTestId('new-session-cwd').fill(minbox.dataDir)
  await shot('00-new-session')
  await page.keyboard.press('Escape')
  await createSession(page, minbox.dataDir, 'api-gateway')
  await expectTerminal(page, 'ready>')
  await typeInTerminal(page, 'say Finished the login page; tests pass.')
  await createSession(page, minbox.dataDir, 'istio-rollout')
  await expectTerminal(page, 'ready>')
  await typeInTerminal(page, 'ask')
  await createSession(page, minbox.dataDir, 'minbox-ui')
  await expectTerminal(page, 'ready>')
  await typeInTerminal(page, 'attach')
  await expectTerminal(page, /sent attach/)
  await typeInTerminal(page, 'review')
  await expectTerminal(page, /sent review/)
  await typeInTerminal(page, 'actions')
  await expectTerminal(page, /sent actions/)
  await typeInTerminal(page, 'stop')
  await expectTerminal(page, /sent stop/)
  await shot('01-list')

  await page.getByTestId('thread-row').filter({ hasText: 'Archive rules' }).click()
  await page.getByTestId('question-card').first().getByRole('radio').first().click()
  await shot('02-thread-1500')
  await page.setViewportSize({ width: 1280, height: 860 })
  await shot('03-thread-1280')
  await page.setViewportSize({ width: 1024, height: 768 })
  await shot('04-thread-1024')
  await page.setViewportSize({ width: 1500, height: 940 })

  await page.getByTestId('thread-back').click()
  await page.getByTestId('thread-row').filter({ hasText: 'The plan' }).click()
  await page.getByTestId('attachment-card').first().click()
  await expect(page.getByTestId('attachment-viewer')).toBeVisible()
  await shot('05-attachment')
  await page.getByTestId('close-file').click()
  await page.getByTestId('thread-back').click()
  await page.getByTestId('thread-row').filter({ hasText: 'Review the store' }).click()
  await page.getByTestId('attachment-card').first().click()
  await expect(page.getByTestId('guided-review')).toBeVisible()
  await shot('06-review')
  await page.getByTestId('review-back').click()

  await page.getByTestId('thread-back').click()
  await page.getByTestId('thread-row').filter({ hasText: 'Before the deploy' }).click()
  await shot('07-actions')

  await page.keyboard.press('Meta+k')
  await page.getByTestId('palette-input').fill('archive')
  await page.waitForTimeout(500)
  await shot('08-search')
  await page.keyboard.press('Escape')

  await page.getByTestId('thread-back').click()
  await page.getByTestId('quick-body').fill('Also check the README')
  await shot('09-compose')

  await page.locator('body').click({ position: { x: 700, y: 5 } })
  await page.keyboard.press('Shift+?')
  await shot('10-shortcuts')
  await page.keyboard.press('Escape')

  await page.getByTestId('open-settings').click()
  await shot('11-settings')
  await page.getByTestId('settings-nav-capabilities').click()
  await page.getByRole('switch', { name: 'Board' }).click()
  await page.getByRole('switch', { name: 'Decision mode' }).click()
  await page.getByTestId('settings-back').click()
  await page.getByTestId('terminal').click()
  await typeInTerminal(page, 'card token bucket')
  await page.getByTestId('open-board').click()
  await shot('12-board')
  await page.keyboard.press('Escape')
  await page.getByTestId('open-decide').click()
  await page.waitForTimeout(800)
  await shot('13-decide')
  await page.keyboard.press('Escape')

  await page.getByTestId('session-row').filter({ hasText: 'minbox-ui' }).click()
  await page.getByTestId('terminal').click()
  await typeInTerminal(page, 'kinds')
  await expectTerminal(page, /sent kinds/)
  await typeInTerminal(page, 'rich')
  await expectTerminal(page, /sent rich/)
  await page.getByTestId('thread-row').filter({ hasText: 'Many kinds' }).click()
  await shot('14-attachments')
  await page.getByRole('button', { name: /Open main\.go/ }).click()
  await shot('15-code-view')
  await page.getByTestId('close-file').click()
  await page.getByTestId('thread-back').click()
  await page.getByTestId('thread-row').filter({ hasText: 'Rich body' }).click()
  await page.waitForTimeout(2500)
  await shot('16-rich-body')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(minbox.url + '/#')
  await shot('20-phone-sessions')
  await page.getByTestId('new-session').click()
  await shot('20-phone-new-session')
  await page.getByRole('button', { name: 'Cancel' }).click()
  await page.getByTestId('session-row').filter({ hasText: 'minbox-ui' }).click()
  await shot('21-phone-inbox')
  await page.getByTestId('thread-row').filter({ hasText: 'Archive rules' }).click()
  await shot('22-phone-thread')
  await page.getByTestId('mobile-tab-terminal').click()
  await shot('23-phone-terminal')
})
